"""Generate theories/Regfile.v from the Sail-generated rv64d_types.v.

The register file is a record with one field per register family of
[type_of_register], so that reads and updates compute without dependent
casts.  Usage: python3 scripts/gen-regfile.py PATH/TO/rv64d_types.v
"""
import re
import sys

src = open(sys.argv[1]).read()
m = re.search(r"Definition type_of_register \(r : register\) : Type :=\n  match r with\n(.*?)\n  end\.", src, re.S)
fams = []
for line in m.group(1).splitlines():
    mm = re.match(r"\s*\| (R_\w+) _ => (.*)$", line)
    fams.append((mm.group(1), mm.group(2)))
fields, rd, up = [], [], []
for c, t in fams:
    f = "f_" + c[2:]
    fields.append(f"  {f} : register_{c[2:]} -> {t};")
    rd.append(f"  | {c} n => {f} rf n")
    others = "; ".join(f"f_{d[2:]} := f_{d[2:]} rf" for d, _ in fams if d != c)
    up.append(f"  | {c} n => fun v => {{| {f} := fun n' => if decide (n = n') then v else {f} rf n'; {others} |}}")
print("""(** * Register file for the Sail RISC-V model (generated by scripts/gen-regfile.py)

    One field per register family of [type_of_register], so that reads
    ([rd]) and updates ([upd_reg]) compute without dependent casts. *)

From stdpp Require Import base.
From SailStdpp Require Import Base.
From Riscv Require Import rv64d_types.
""")
print("Record regfile : Type := mkRegfile {\n" + "\n".join(fields) + "\n}.\n")
print("(** The value of register [r]. *)\nDefinition rd (rf : regfile) (r : register) : type_of_register r :=\n  match r return type_of_register r with\n" + "\n".join(rd) + "\n  end.\n")
print("(** Update register [r]. *)\nDefinition upd_reg (rf : regfile) (r : register) : type_of_register r -> regfile :=\n  match r return type_of_register r -> regfile with\n" + "\n".join(up) + "\n  end.")
print("\n(** Every register at an arbitrary (inhabitant) value. *)\nDefinition default_regfile : regfile := mkRegfile " + " ".join(["(fun _ => inhabitant)"] * len(fams)) + ".")
